#!/usr/bin/env python3
"""Build comparable GPCR fingerprints from per-structure GPCRdb mapping tables.

Inputs are mapping TSVs (chain, resi, aa, gpcrdb, segment) generated by
gpcrdb_auto_mapping.py or GPCRdb-derived exports. All structures get exactly
the same generic-position feature universe. Missing mapping is never encoded
as a zero interaction: use --missing-policy reject for matrix-safe results.
"""
import argparse
import csv
import json
from pathlib import Path

def sort_key(value):
    import re
    m = re.fullmatch(r"(\d+)x(\d+)", value)
    if not m:
        raise ValueError(f"Not a GPCRdb generic number: {value}")
    helix, digits = int(m[1]), m[2]
    rank = {1:0,12:1,2:2,23:3,3:4,34:5,4:6,45:7,5:8,56:9,6:10,67:11,7:12,8:13}
    return rank.get(helix,99), digits[:2], len(digits), digits[2:]

def load_mapping(path):
    with open(path, newline="", encoding="utf-8-sig") as stream:
        rows = list(csv.DictReader(stream, delimiter="\t"))
    if not rows:
        raise ValueError(f"Empty mapping: {path}")
    required = {"chain", "resi", "gpcrdb"}
    if not required.issubset(rows[0]):
        raise ValueError(f"Missing mapping columns in {path}: {required - set(rows[0])}")
    result = {}
    for row in rows:
        position = (row.get("gpcrdb") or "").strip()
        if not position:
            continue
        sort_key(position)
        if position in result:
            raise ValueError(f"Duplicate GPCRdb position {position} in {path}")
        chain, resi = row["chain"].strip(), row["resi"].strip()
        if not chain or not resi:
            raise ValueError(f"Missing chain or residue for {position} in {path}")
        result[position] = (chain, resi, (row.get("aa") or "").strip(),
                            (row.get("segment") or "").strip())
    if not result:
        raise ValueError(f"No numbered residues in {path}")
    return result

def create(files, outdir, positions_file=None, mode="intersection", missing_policy="reject"):
    if mode not in ("union", "intersection"):
        raise ValueError("mode must be union or intersection")
    if missing_policy not in ("reject", "report"):
        raise ValueError("missing_policy must be reject or report")
    mappings = [(Path(filename), load_mapping(filename)) for filename in files]
    if len({path.stem for path,_ in mappings}) != len(mappings):
        raise ValueError("Mapping filenames must have unique stems")
    keys = [set(mapping) for _,mapping in mappings]
    if positions_file:
        positions = []
        for line in Path(positions_file).read_text().splitlines():
            line = line.split("#",1)[0]
            positions.extend(line.replace(","," ").split())
        for p in positions:
            sort_key(p)
        universe = set(positions)
    elif mode == "union":
        universe = set.union(*keys)
    else:
        universe = set.intersection(*keys)
    positions = sorted(universe, key=sort_key)
    if not positions:
        raise ValueError("No shared generic positions")
    audit = {"mode": mode, "missing_policy": missing_policy,
             "positions": positions, "structures": []}
    for path, mapping in mappings:
        missing = [p for p in positions if p not in mapping]
        audit["structures"].append({"mapping":str(path), "missing":missing,
                                    "covered":len(positions)-len(missing),
                                    "total":len(positions)})
    folder = Path(outdir)
    folder.mkdir(parents=True,exist_ok=True)
    (folder/"common_gpcrdb_positions.txt").write_text("\n".join(positions)+"\n")
    (folder/"coverage_audit.json").write_text(json.dumps(audit,indent=2)+"\n")
    if missing_policy=="reject" and any(item["missing"] for item in audit["structures"]):
        raise ValueError("Missing generic positions in one or more structures; "
                         "see coverage_audit.json. Use --mode intersection or "
                         "--missing-policy report for partial exploratory sets.")
    colors = {"TM1":"#ffa8a8","TM2":"#ffd8a8","TM3":"#ffec99","TM4":"#b2f2bb",
              "TM5":"#99e9f2","TM6":"#a5d8ff","TM7":"#d0bfff"}
    three_letter = dict(zip("ARNDCEQGHILKMFPSTWYV",
        "ALA ARG ASN ASP CYS GLU GLN GLY HIS ILE LEU LYS MET PHE PRO SER THR TRP TYR VAL".split()))
    for path,mapping in mappings:
        lines=["@name GPCR shared generic pocket ("+path.stem+")"]
        used={mapping[p][3] for p in positions if p in mapping}
        lines.extend(f"@color {seg} {col}" for seg,col in colors.items() if seg in used)
        for pos in positions:
            if pos not in mapping:
                continue  # explicitly missing, never invented
            chain,resi,aa,segment=mapping[pos]
            label = three_letter.get(aa.upper(), aa.upper())
            lines.append("\t".join((chain,resi,pos,segment or f"TM{pos.split('x')[0]}",label)))
        (folder/(path.stem+".pocket.tsv")).write_text("\n".join(lines)+"\n")
    return audit

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("mapping",nargs="+",help="Per-structure GPCRdb mapping TSV files")
    p.add_argument("--output-dir",required=True)
    p.add_argument("--positions",help="Curated GPCRdb position list, used instead of union/intersection")
    p.add_argument("--mode",choices=["union","intersection"],default="intersection")
    p.add_argument("--missing-policy",choices=["reject","report"],default="reject")
    args=p.parse_args()
    try:
        audit=create(args.mapping,args.output_dir,args.positions,args.mode,args.missing_policy)
    except Exception as e:
        p.exit(1,"GPCR shared fingerprint error: "+str(e)+"\n")
    print(json.dumps({"positions":len(audit["positions"]),
                      "structures":len(audit["structures"]),
                      "audit":str(Path(args.output_dir)/"coverage_audit.json")},indent=2))

if __name__=="__main__":
    main()
